class PipelineResult:
    """Container for all topology pipeline outputs."""
    __slots__ = (
        "occ", "inflated", "sdf", "cost",
        "G_voronoi", "G_separated", "door_field",
        "objects", "doors", "rog",
    )

def run_topology_pipeline(
    occ: np.ndarray,
    objects: list[ObjectInfo],
    doors: list[DoorInfo],
) -> PipelineResult:
    """
    Run the full topology pipeline using core algorithms.
    No algorithmic code here — only orchestration and timing.
    """
    res = PipelineResult()
    res.occ = occ
    res.objects = objects
    res.doors = doors

    # Step 1: Inflation
    print("  [1/6] Inflating occupancy...")
    t0 = time.perf_counter()
    res.inflated = inflate_occupancy(
        occ, resolution=RESOLUTION,
        params=InflationParams(radius_m=0.15),
    )
    print(f"         {(time.perf_counter()-t0)*1000:.1f} ms")

    # Step 2: SDF
    print("  [2/6] Computing SDF...")
    t0 = time.perf_counter()
    res.sdf = compute_sdf(res.inflated, resolution=RESOLUTION)
    print(f"         {(time.perf_counter()-t0)*1000:.1f} ms")

    # Step 3: Boundary cost field
    print("  [3/6] Computing boundary cost field...")
    t0 = time.perf_counter()
    res.cost = boundary_cost_field(
        res.inflated, resolution=RESOLUTION, distance_scale_m=1.5,
    )
    print(f"         {(time.perf_counter()-t0)*1000:.1f} ms")

    # Step 4: Voronoi topology graph
    print("  [4/6] Extracting Voronoi graph...")
    t0 = time.perf_counter()
    res.G_voronoi = extract_voronoi_graph(
        res.inflated, resolution=RESOLUTION,
        params=TopologyParams(
            sdf_scale_m=1.5,
            inner_inflate_m=0.15,
            sparsify_dist_m=0.3,
            min_component=4,
        ),
    )
    print(f"         {(time.perf_counter()-t0)*1000:.1f} ms  |  "
          f"Nodes: {len(res.G_voronoi.nodes)}, Edges: {len(res.G_voronoi.edges)}")

    # Step 5: Room separation via doors
    print("  [5/6] Separating rooms...")
    t0 = time.perf_counter()
    res.G_separated, res.door_field = separate_rooms(
        res.G_voronoi,
        grid_shape=occ.shape,
        doors=doors,
        resolution=RESOLUTION,
        params=RoomSeparationParams(edge_score_threshold=0.05, min_component=4),
    )
    n_rooms = nx.number_connected_components(res.G_separated)
    print(f"         {(time.perf_counter()-t0)*1000:.1f} ms  |  Rooms: {n_rooms}")

    # Step 6: Assign objects to rooms & build room–object graph
    print("  [6/6] Building room–object graph...")
    t0 = time.perf_counter()
    assign_objects_to_rooms(objects, res.G_separated)
    res.rog = build_room_object_graph(res.G_separated, objects)
    print(f"         {(time.perf_counter()-t0)*1000:.1f} ms")

    return res


