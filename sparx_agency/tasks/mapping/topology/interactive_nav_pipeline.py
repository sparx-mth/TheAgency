def discover_maps() -> list[str]:
    """Return sorted list of available map folder names."""
    if not os.path.isdir(_MAPS_DIR):
        return []
    return sorted(
        d for d in os.listdir(_MAPS_DIR)
        if os.path.isfile(os.path.join(_MAPS_DIR, d, "occupancy.npy"))
    )


def load_map(name: str) -> tuple[np.ndarray, list[ObjectInfo], list[DoorInfo], dict]:
    """
    Load a map from disk.

    Returns
    -------
    occ : np.ndarray          uint8 occupancy grid
    objects : list[ObjectInfo] objects with position/bbox (no room_id yet)
    doors : list[DoorInfo]     door openings
    meta : dict                metadata dict
    """
    map_dir = os.path.join(_MAPS_DIR, name)

    occ = np.load(os.path.join(map_dir, "occupancy.npy"))

    with open(os.path.join(map_dir, "objects.json")) as f:
        raw_objs = json.load(f)
    objects = [
        ObjectInfo(
            name=o["name"],
            position=np.array(o["position"]),
            bbox=tuple(o["bbox"]),
            semantic_class=o["semantic_class"],
        )
        for o in raw_objs
    ]

    with open(os.path.join(map_dir, "doors.json")) as f:
        raw_doors = json.load(f)
    doors = [
        DoorInfo(
            position=np.array(d["position"]),
            size=np.array(d["size"]),
        )
        for d in raw_doors
    ]

    with open(os.path.join(map_dir, "metadata.json")) as f:
        meta = json.load(f)

    return occ, objects, doors, meta


