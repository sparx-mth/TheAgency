def _show_figure_interactive(fig, title: str = "Figure", on_click=None):
    """
    Display a matplotlib Figure in a real tkinter window.
    Blocks until the user closes the window.

    Parameters
    ----------
    fig : matplotlib.figure.Figure
    title : str        Window title
    on_click : callable or None
        If given, connected as a button_press_event callback.
        When on_click calls root.quit(), the window closes.
    """
    root = tk.Tk()
    root.title(title)
    root.protocol("WM_DELETE_WINDOW", root.quit)

    canvas = FigureCanvasTkAgg(fig, master=root)
    canvas.draw()
    canvas.get_tk_widget().pack(side=tk.TOP, fill=tk.BOTH, expand=True)

    toolbar = NavigationToolbar2Tk(canvas, root)
    toolbar.update()

    cid = None
    if on_click is not None:
        cid = canvas.mpl_connect("button_press_event",
                                  lambda event: on_click(event, fig, canvas, root))

    root.mainloop()

    if cid is not None:
        canvas.mpl_disconnect(cid)

    try:
        root.destroy()
    except tk.TclError:
        pass  # already destroyed


