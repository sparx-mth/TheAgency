def click_robot_position(res: PipelineResult, map_name: str) -> tuple[float, float]:
    """
    Open an interactive tkinter window. User clicks to place the robot.
    Returns (row, col) in grid coordinates.
    """
    result = {"pos": None}

    fig, ax = show_interactive_map(res, map_name)

    def on_click(event, fig, canvas, root):
        if event.inaxes != ax:
            return
        col, row = event.xdata, event.ydata
        r, c = int(round(row)), int(round(col))

        # Reject clicks on occupied cells
        if r < 0 or r >= res.occ.shape[0] or c < 0 or c >= res.occ.shape[1]:
            print(f"  ✗ Position ({r}, {c}) is out of bounds.")
            return
        if res.occ[r, c] != 0 or res.inflated[r, c] != 0:
            print(f"  ✗ Position ({r}, {c}) is occupied — click on a free cell.")
            return

        result["pos"] = (r, c)
        # Draw robot marker
        ax.plot(c, r, "D", color="red", markersize=14,
                markeredgecolor="white", markeredgewidth=2, zorder=10)
        ax.annotate("ROBOT", (c, r), fontsize=8, fontweight="bold",
                    color="red", ha="center", va="bottom",
                    xytext=(0, 10), textcoords="offset points")
        canvas.draw()
        print(f"  ✓ Robot placed at row={r}, col={c}")

        # Close the window after a brief pause
        root.after(500, root.quit)

    print("\n  👆 Click on the map to place the robot...")
    print("     (click on a free white/light-grey cell)")
    _show_figure_interactive(fig, title=f"{map_name} — Click to place robot",
                             on_click=on_click)

    if result["pos"] is None:
        print("  ⚠ No position clicked — using map centre as fallback.")
        H, W = res.occ.shape
        result["pos"] = (H // 2, W // 2)

    return result["pos"]


