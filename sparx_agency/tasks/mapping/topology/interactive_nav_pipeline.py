def _room_colors(n: int):
    """Generate n distinct room colors."""
    return plt.cm.Set2(np.linspace(0, 1, max(n, 1)))


def plot_pipeline_summary(res: PipelineResult, map_name: str):
    """Show a 2×3 summary of pipeline stages."""
    fig = Figure(figsize=(20, 11))
    axes = fig.subplots(2, 3)
    fig.suptitle(f"Topology Pipeline — {map_name}", fontsize=14, fontweight="bold")
    occ, inflated = res.occ, res.inflated

    # 1. Raw occupancy
    axes[0, 0].imshow(occ != 0, cmap="gray_r", interpolation="nearest")
    axes[0, 0].set_title("1. Raw Occupancy")
    axes[0, 0].set_axis_off()

    # 2. Inflated
    rgb = np.ones((*inflated.shape, 3))
    rgb[inflated != 0] = [1.0, 0.7, 0.7]
    rgb[occ != 0] = [0.0, 0.0, 0.0]
    axes[0, 1].imshow(rgb, interpolation="nearest")
    axes[0, 1].set_title("2. Inflated Occupancy")
    axes[0, 1].set_axis_off()

    # 3. SDF
    vmax = np.abs(res.sdf).max()
    im = axes[0, 2].imshow(res.sdf, cmap="RdBu", vmin=-vmax, vmax=vmax,
                            interpolation="nearest")
    fig.colorbar(im, ax=axes[0, 2], fraction=0.046, pad=0.04, label="meters")
    axes[0, 2].set_title("3. Signed Distance Field")
    axes[0, 2].set_axis_off()

    # 4. Voronoi graph
    _draw_voronoi(axes[1, 0], occ, inflated, res.G_voronoi, "4. Voronoi Graph")

    # 5. Room separation
    _draw_rooms(axes[1, 1], occ, inflated, res.G_separated, "5. Room Separation")

    # 6. Room–object graph
    _draw_room_objects(axes[1, 2], occ, inflated, res.G_separated,
                       res.rog, res.objects, "6. Room–Object Graph")

    fig.tight_layout()
    _show_figure_interactive(fig, title=f"Pipeline — {map_name}")
    return fig


def _draw_voronoi(ax, occ, inflated, G, title):
    rgb = np.ones((*occ.shape, 3)) * 0.95
    rgb[inflated != 0] = [0.85, 0.85, 0.85]
    rgb[occ != 0] = [0.2, 0.2, 0.2]
    ax.imshow(rgb, interpolation="nearest")

    if len(G.nodes) == 0:
        ax.set_title(f"{title} (empty)")
        ax.set_axis_off()
        return

    junctions = set(get_junctions(G))
    dead_ends = set(get_dead_ends(G))
    passthrough = set(G.nodes) - junctions - dead_ends

    for u, v in G.edges():
        ax.plot([u[1], v[1]], [u[0], v[0]], color="#4488cc", lw=0.6, alpha=0.7)

    def _scatter(nodes, c, s, label):
        if nodes:
            arr = np.array(list(nodes))
            ax.scatter(arr[:, 1], arr[:, 0], c=c, s=s, zorder=5,
                       label=label, edgecolors="none")

    _scatter(passthrough, "#4488cc", 3, f"Pass-through [{len(passthrough)}]")
    _scatter(junctions, "#ff3333", 30, f"Junctions [{len(junctions)}]")
    _scatter(dead_ends, "#33cc33", 18, f"Dead-ends [{len(dead_ends)}]")

    ax.legend(loc="upper right", fontsize=6, framealpha=0.9)
    ax.set_title(title)
    ax.set_axis_off()


def _draw_rooms(ax, occ, inflated, G_sep, title):
    rgb = np.ones((*occ.shape, 3)) * 0.95
    rgb[inflated != 0] = [0.85, 0.85, 0.85]
    rgb[occ != 0] = [0.2, 0.2, 0.2]
    ax.imshow(rgb, interpolation="nearest")

    components = list(nx.connected_components(G_sep))
    cmap = _room_colors(len(components))
    for ci, comp in enumerate(components):
        color = cmap[ci % len(cmap)][:3]
        sub = G_sep.subgraph(comp)
        for u, v in sub.edges():
            ax.plot([u[1], v[1]], [u[0], v[0]], color=color, lw=1.0, alpha=0.8)
        arr = np.array(list(comp))
        ax.scatter(arr[:, 1], arr[:, 0], c=[color], s=6, zorder=5,
                   label=f"Room {ci}", edgecolors="none")

    ax.legend(loc="upper right", fontsize=6, framealpha=0.9)
    ax.set_title(title)
    ax.set_axis_off()


def _draw_room_objects(ax, occ, inflated, G_sep, rog, objects, title):
    rgb = np.ones((*occ.shape, 3)) * 0.95
    rgb[inflated != 0] = [0.90, 0.90, 0.90]
    rgb[occ != 0] = [0.2, 0.2, 0.2]
    ax.imshow(rgb, interpolation="nearest")

    components = list(nx.connected_components(G_sep))
    cmap = _room_colors(len(components))

    # Room Voronoi edges
    for ci, comp in enumerate(components):
        color = cmap[ci % len(cmap)][:3]
        sub = G_sep.subgraph(comp)
        for u, v in sub.edges():
            ax.plot([u[1], v[1]], [u[0], v[0]], color=color, lw=0.5, alpha=0.35)

    # Room centre stars
    for rname in get_room_nodes(rog):
        rd = rog.nodes[rname]
        rc, cc = rd["pos_map"]
        color = cmap[rd["room_id"] % len(cmap)][:3]
        ax.plot(cc, rc, marker="*", color=color, markersize=14,
                markeredgecolor="k", markeredgewidth=0.5, zorder=7)
        ax.annotate(rname, (cc, rc), fontsize=7, fontweight="bold",
                    color=color, ha="left", va="bottom",
                    xytext=(4, 4), textcoords="offset points")

    # Object markers
    for obj in objects:
        if obj.room_id is None or obj.room_id < 0:
            continue
        color = cmap[obj.room_id % len(cmap)][:3]
        r, c = obj.position
        ax.plot(c, r, "o", color=color, markersize=7,
                markeredgecolor="k", markeredgewidth=0.6, zorder=6)
        ax.annotate(obj.name, (c, r), fontsize=5, ha="left", va="top",
                    color="k", xytext=(3, -3), textcoords="offset points")

    ax.set_title(title)
    ax.set_axis_off()


