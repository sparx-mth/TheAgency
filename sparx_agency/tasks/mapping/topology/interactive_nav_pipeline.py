def print_room_hierarchy(rog: nx.DiGraph, objects: list[ObjectInfo]):
    """Pretty-print the room–object tree."""
    print("\n  Room–Object Hierarchy")
    print("  " + "=" * 45)
    for rname in sorted(get_room_nodes(rog)):
        rd = rog.nodes[rname]
        obj_names = get_objects_in_room(rog, rd["room_id"])
        print(f"    ★ {rname}  (centre: {rd['pos_map']})")
        if obj_names:
            for i, oname in enumerate(obj_names):
                od = rog.nodes[oname]
                branch = "├─" if i < len(obj_names) - 1 else "└─"
                print(f"      {branch} {oname:18s}  [{od['semantic_class']}]")
        else:
            print(f"      └─ (no objects)")
    print()


