def ollama_backend(model: str = "llama3.1:8b") -> Callable[[str], str]:
    """Ollama LLM backend via subprocess."""

    # ── Connectivity test — fail fast if Ollama isn't running ──
    test = subprocess.run(
        "ollama list", shell=True, capture_output=True, text=True, timeout=10,
    )
    if test.returncode != 0:
        raise RuntimeError(
            f"Ollama is not running.\n"
            f"   Start it with:  ollama serve\n"
            f"   stderr: {test.stderr.strip()}"
        )

    # Verify the requested model is available
    if model not in test.stdout:
        print(f"   ⚠ Model '{model}' not found. Available models:")
        print(f"     {test.stdout.strip()}")
        print(f"   Pull it with:  ollama pull {model}")
        raise RuntimeError(f"Model '{model}' not available in Ollama.")

    def call(prompt: str) -> str:
        with tempfile.NamedTemporaryFile(mode="w", delete=False, suffix=".txt") as f:
            f.write(prompt)
            tmp = f.name
        try:
            result = subprocess.run(
                f'cat "{tmp}" | ollama run {model}',
                shell=True, capture_output=True, text=True, timeout=180,
            )
            if result.returncode != 0:
                raise RuntimeError(f"Ollama error: {result.stderr.strip()}")
            return result.stdout.strip()
        finally:
            os.unlink(tmp)
    return call


