    def smooth_depth_map(self, raw_depth_map: np.ndarray) -> np.ndarray:
        raw_depth_map = raw_depth_map.astype(np.float32)

        if self.last_smoothed_depth is None:
            self.last_smoothed_depth = raw_depth_map
        elif self.last_smoothed_depth.shape != raw_depth_map.shape:
            self.get_logger().warn(
                "[Depth] Depth shape changed, resetting EMA smoothing buffer"
            )
            self.last_smoothed_depth = raw_depth_map
        else:
            self.last_smoothed_depth = (
                self.ema_alpha * raw_depth_map
                + (1.0 - self.ema_alpha) * self.last_smoothed_depth
            )

        return self.last_smoothed_depth.astype(np.float32)

    def update_center_depth(self, depth_map: np.ndarray):
        if self.cx is None or self.cy is None:
            return

        H, W = depth_map.shape[:2]
        u_idx = int(round(self.cx))
        v_idx = int(round(self.cy))

        if not (0 <= u_idx < W and 0 <= v_idx < H):
            return

        half_side = 2
        x0 = max(0, u_idx - half_side)
        x1 = min(W, u_idx + half_side + 1)
        y0 = max(0, v_idx - half_side)
        y1 = min(H, v_idx + half_side + 1)

        center_region = depth_map[y0:y1, x0:x1]
        valid_center_depths = center_region[
            np.isfinite(center_region) & (center_region > 0)
        ]

        if valid_center_depths.size > 0:
            self.center_depth = float(np.mean(valid_center_depths) * self.depth_scale)

    # ============================================================
    # Metric velocity from optical flow + depth
    # ============================================================
    def velocity_from_flow_and_depth(self, good_old, good_new, depth_map, dt: float):
        """
        Estimate metric velocity from pixel optical flow and depth.

        Returns:
            vx, vy, vz, n_used

        The final axis convention is kept from your existing implementation:
            return Vz_o, -Vx_o, -Vy_o
        """
        if dt <= 0.0:
            return 0.0, 0.0, 0.0, 0

        H, W = depth_map.shape[:2]

        du = (good_new[:, 0] - good_old[:, 0]) / dt
        dv = (good_new[:, 1] - good_old[:, 1]) / dt

        u_int = np.rint(good_new[:, 0]).astype(np.int32)
        v_int = np.rint(good_new[:, 1]).astype(np.int32)

        valid = (
            (u_int >= 0) & (u_int < W) &
            (v_int >= 0) & (v_int < H)
        )

        if not np.any(valid):
            return 0.0, 0.0, 0.0, 0

        Z = np.zeros_like(du, dtype=np.float32)
        Z[valid] = depth_map[v_int[valid], u_int[valid]] * self.depth_scale

        valid = (
            valid &
            np.isfinite(Z) &
            (Z > self.min_depth) &
            (Z < self.max_depth)
        )

        nv = int(np.sum(valid))
        if nv < 8:
            return 0.0, 0.0, 0.0, nv

        u_c_v = good_old[valid, 0].astype(np.float64) - float(self.cx)
        v_c_v = good_old[valid, 1].astype(np.float64) - float(self.cy)

        Zv = Z[valid].astype(np.float64)
        du_v = du[valid].astype(np.float64)
        dv_v = dv[valid].astype(np.float64)

        #  Outlier Rejection use RANSAC 
        vx_estimates = - (du_v * Zv) / float(self.fx)
        vy_estimates = - (dv_v * Zv) / float(self.fy)

        median_vx = np.median(vx_estimates)
        median_vy = np.median(vy_estimates)

        dev_x = np.abs(vx_estimates - median_vx)
        dev_y = np.abs(vy_estimates - median_vy)

        threshold = 0.3  # Tunable threshold for outlier rejection
        good_inliers = (dev_x < threshold) & (dev_y < threshold)

        nv_inliers = int(np.sum(good_inliers))
        if nv_inliers < 8:
            return 0.0, 0.0, 0.0, 0

        u_c_v_in = u_c_v[good_inliers]
        v_c_v_in = v_c_v[good_inliers]
        Zv_in = Zv[good_inliers]
        du_v_in = du_v[good_inliers]
        dv_v_in = dv_v[good_inliers]



        A = np.zeros((2 * nv_inliers, 3), dtype=np.float64)
        B = np.zeros((2 * nv_inliers,), dtype=np.float64)

        A[0::2, 0] = -float(self.fx)
        A[0::2, 2] = u_c_v_in
        B[0::2] = du_v_in * Zv_in

        A[1::2, 1] = -float(self.fy)
        A[1::2, 2] = v_c_v_in
        B[1::2] = dv_v_in * Zv_in

        dist_sq = u_c_v_in**2 + v_c_v_in**2
        denom = 0.05 * (float(self.cx) ** 2 + float(self.cy) ** 2)
        weights = np.exp(-dist_sq / max(denom, 1e-9))

        W_vec = np.zeros((2 * nv_inliers,), dtype=np.float64)
        W_vec[0::2] = weights
        W_vec[1::2] = weights
        sqrt_w = np.sqrt(W_vec)

        try:
            vel, *_ = np.linalg.lstsq(
                A * sqrt_w[:, np.newaxis],
                B * sqrt_w,
                rcond=None,
            )
        except np.linalg.LinAlgError:
            return 0.0, 0.0, 0.0, nv_inliers

        Vx_o = float(vel[0])
        Vy_o = float(vel[1])
        Vz_o = float(vel[2])

        return Vz_o, -Vx_o, -Vy_o, nv_inliers

