class FlowDepthVelocityNode(Node):
    """
    Flow + Depth velocity node with delayed-depth support.

    Architecture:
      1. RGB callback runs immediately when an RGB frame arrives.
         It computes Optical Flow in pixel space using consecutive RGB frames.
         The flow result is stored in pending_flow_queue.

      2. Depth callback runs when a Depth frame arrives, possibly later than RGB.
         It finds the matching pending Optical Flow result and converts the
         pixel motion to metric velocity using the Depth map.

    Why this is useful:
      - RGB can be faster than Depth.
      - Depth may be generated by a model and arrive with latency.
      - We do not want ApproximateTimeSynchronizer to block RGB processing.
    """

